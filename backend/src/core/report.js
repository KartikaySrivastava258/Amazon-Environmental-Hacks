// Brand diagnostic report (PDF). Built ONLY from consented, anonymous aggregates (AGG#<brand>#<model>):
// no job, owner, phone, address, token, photo or note ever reaches this module, so none can reach the PDF.
// Shares are within one model; models and brands are never ranked by raw counts (sales volume bias).
import { CATEGORIES, CAUSES, SEVERITY, BARRIERS, MIN_SAMPLE, areaName, BRANDS } from './catalog.js';
import { buildModelReport, modelScores } from './insights.js';

export const HOTSPOT_RULE = { minRecords: 8, minRatio: 1.8 };
const pct = (x) => `${Math.round((Number(x) || 0) * 100)}%`;
const int = (n) => Math.round(Number(n) || 0).toLocaleString('en-IN');
const compEn = (cat, id) => CATEGORIES[cat]?.components.find((c) => c.id === id)?.en || id;
const MONTH = /^\d{4}-(0[1-9]|1[0-2])$/;

export function validMonth(m) { return MONTH.test(String(m || '')); }

/** Monthly counts inside [from, to] (inclusive, 'YYYY-MM'); null bounds are open. */
function inRange(months, from, to) {
  return months.filter(([m]) => (!from || m >= from) && (!to || m <= to)).reduce((s, [, v]) => s + v, 0);
}

export function reportFilename({ brand, model, category, generatedAt }) {
  const scope = model || category || 'all';
  return `punarnava-${brand}-${scope}-${String(generatedAt).slice(0, 10)}.pdf`.replace(/[^A-Za-z0-9._-]+/g, '-');
}

/**
 * models: [{ model, category, total, comps, alerts }] for ONE brand. filters: { model?, category?, from?, to? }.
 * Returns { doc (for renderPdf), facts (what the report states, for the UI and tests) }.
 */
export function buildReportDoc({ brand, models, filters = {}, generatedAt, detector = null }) {
  const { from = null, to = null } = filters;
  const dated = !!(from || to);
  const reports = models.map((m) => {
    const r = buildModelReport(m.total || { brand, model: m.model, category: m.category, n: 0, n_syn: 0 }, m.comps || [], m.alerts || []);
    r.category = r.category || m.category;
    r.model = r.model || m.model;
    r.scores = m.total ? modelScores(m.total, m.comps || []) : { n: 0, sufficient: false };
    r.inPeriod = dated ? r.components.reduce((s, c) => s + inRange(c.months, from, to), 0) : null;
    return r;
  }).sort((a, b) => String(a.model).localeCompare(String(b.model))); // alphabetical, never by volume
  const n = reports.reduce((s, r) => s + r.n, 0);
  const synN = reports.reduce((s, r) => s + Math.round(r.n * r.syntheticShare), 0);
  const realN = n - synN;
  const synShare = n ? synN / n : 0;
  const insufficient = reports.every((r) => r.n < MIN_SAMPLE);
  const scope = filters.model ? `Model ${filters.model}` : filters.category ? `All ${brand} models in ${CATEGORIES[filters.category]?.en || filters.category}` : `All ${brand} models`;
  const period = dated ? `${from || 'start'} to ${to || 'latest'}` : 'All months on record';
  const facts = {
    brand, scope, filters: { model: filters.model || null, category: filters.category || null, from, to }, period,
    generatedAt, models: reports.map((r) => r.model), sampleSize: n, realRecords: realN, syntheticRecords: synN,
    syntheticShare: synShare, insufficient, minSample: MIN_SAMPLE,
  };

  const B = [];
  B.push({ h1: 'Component Intelligence diagnostic report' });
  B.push({ p: `${brand}. Generated by Punarnava from consented, anonymous repair records.`, color: 'muted' });
  B.push({ kv: [
    ['Generated', `${String(generatedAt).replace('T', ' ').slice(0, 16)} UTC`],
    ['Brand', brand],
    ['Scope (model / category)', scope],
    ['Category', [...new Set(reports.map((r) => CATEGORIES[r.category]?.en || r.category))].join(', ') || '-'],
    ['Date filter', period],
    ['Sample size', `${int(n)} records: ${int(realN)} real, ${int(synN)} synthetic${dated ? `; ${int(reports.reduce((s, r) => s + (r.inPeriod || 0), 0))} in the selected months` : ''}`],
    ['Minimum sample', `${MIN_SAMPLE} records per component insight`],
  ] });
  if (synN > 0) B.push({ banner: `CONTAINS SYNTHETIC DEMO DATA: ${int(synN)} of ${int(n)} records (${pct(synShare)}) are labelled synthetic test data, not real repairs. Do not use synthetic findings for product decisions.`, tone: 'syn' });
  else if (n > 0) B.push({ banner: `All ${int(n)} records are real repairs logged on Punarnava with the owner's consent. No synthetic data.`, tone: 'ok' });
  if (insufficient) B.push({ banner: `INSUFFICIENT DATA: ${int(n)} record(s) in scope. At least ${MIN_SAMPLE} records per component are needed before Punarnava reports a pattern, so this report lists counts only and makes no findings.`, tone: 'warn' });

  // 1. Executive summary
  B.push({ h2: '1. Executive summary' });
  if (!reports.length) B.push({ p: 'No models matched these filters. Insufficient data.' });
  for (const r of reports) {
    const top = r.components[0];
    const cat = CATEGORIES[r.category]?.en || r.category;
    const real = Math.round(r.n * (1 - r.syntheticShare));
    let line = `${r.model} (${cat}): ${int(r.n)} records (${int(real)} real, ${int(r.n - real)} synthetic).`;
    if (r.n < MIN_SAMPLE) line += ` Insufficient data: fewer than ${MIN_SAMPLE} records, so no findings are reported for this model.`;
    else if (top) line += ` Most frequently reported failing component within this model: ${compEn(r.category, top.component)} (${pct(top.share)} of this model's records${top.sufficient ? '' : '; below the minimum sample'}). ${r.recommendations.length} design recommendation(s); ${r.alerts.length} early-warning alert(s).`;
    if (dated) line += ` Records in the selected months: ${int(r.inPeriod)}.`;
    B.push({ p: line });
  }
  B.push({ small: 'Data quality: records come from technician diagnoses that the owner agreed to share anonymously. Shares compare components within one model only; a model with more sales simply has more records, so raw counts are never used to rank models or brands.' });

  // 2. Failing components
  B.push({ h2: '2. Most frequently reported failing components (share within each model)' });
  for (const r of reports) {
    B.push({ h3: `${r.model}: ${int(r.n)} records` });
    if (!r.components.length) { B.push({ p: 'Insufficient data: no component records for this model.' }); continue; }
    B.push({ bars: r.components.slice(0, 8).map((c) => ({ label: compEn(r.category, c.component), value: c.share, text: `${pct(c.share)} (n=${int(c.n)})`, tone: c.sufficient ? '' : 'red' })) });
    if (r.components.slice(0, 8).some((c) => !c.sufficient)) B.push({ small: `Red bars: fewer than ${MIN_SAMPLE} records, so no findings are drawn for that component.` });
    const cols = [
      { label: 'Component', w: 0.25 }, { label: 'Records', w: 0.1, align: 'right' }, { label: 'Share of model', w: 0.12, align: 'right' },
      { label: 'Synthetic', w: 0.11, align: 'right' }, { label: 'Typical age', w: 0.11 }, { label: 'Failed < 2 yrs', w: 0.11, align: 'right' },
    ];
    if (dated) cols.push({ label: 'In period', w: 0.1, align: 'right' });
    cols.push({ label: 'Sample', w: dated ? 0.1 : 0.2 });
    for (const c of cols) c.w = c.w / cols.reduce((s, x) => s + x.w, 0);
    B.push({ table: { cols, rows: r.components.map((c) => [
      compEn(r.category, c.component), int(c.n), pct(c.share), pct(c.syntheticShare), c.medianBand ? `${c.medianBand} yrs` : '-', pct(c.earlyShare),
      ...(dated ? [int(inRange(c.months, from, to))] : []),
      c.sufficient ? 'OK' : 'Insufficient',
    ]) } });
  }

  // 3. Causes, severity, barriers
  B.push({ h2: '3. Technician-recorded causes, severity and repair barriers (aggregated, anonymised)' });
  B.push({ small: 'Technicians record the failed component, up to three likely causes, the severity and any repair barrier. Free-text notes, photos and voice notes are not included in brand reports. Causes can overlap, so shares may add up to more than 100%.' });
  for (const r of reports) {
    const ok = r.components.filter((c) => c.sufficient).slice(0, 5);
    B.push({ h3: r.model });
    if (!ok.length) { B.push({ p: `Insufficient data: no component of ${r.model} has ${MIN_SAMPLE} or more records.` }); continue; }
    B.push({ table: {
      cols: [{ label: 'Component', w: 0.22 }, { label: 'Top causes (share of component records)', w: 0.42 }, { label: 'Severity (real records)', w: 0.36 }],
      rows: ok.map((c) => {
        const sevN = c.severity.reduce((s, x) => s + x.n, 0);
        const sev = sevN ? c.severity.map((x) => `${SEVERITY[x.severity]?.en || x.severity} ${pct(x.n / sevN)}`).join('; ') + ` (n=${sevN})` : 'Not recorded (synthetic or older records)';
        return [compEn(r.category, c.component), c.causes.slice(0, 3).map((x) => `${CAUSES[x.cause]?.en || x.cause} ${pct(x.share)}`).join('; '), sev];
      }),
    } });
  }

  // 4. Parts availability and regions
  B.push({ h2: '4. Parts availability gaps and regional patterns' });
  for (const r of reports) {
    const ok = r.components.filter((c) => c.sufficient);
    B.push({ h3: r.model });
    if (!ok.length) { B.push({ p: 'Insufficient data for parts availability or regional patterns.' }); continue; }
    B.push({ table: {
      cols: [{ label: 'Component', w: 0.26 }, { label: 'No spare available', w: 0.17, align: 'right' }, { label: 'Repair abandoned', w: 0.17, align: 'right' }, { label: 'Main repair barrier', w: 0.4 }],
      rows: ok.map((c) => [compEn(r.category, c.component), pct(c.spareNoneShare), pct(c.abandonedShare), c.barriers[0] ? `${BARRIERS[c.barriers[0].barrier]?.en || c.barriers[0].barrier} ${pct(c.barriers[0].share)}` : 'None recorded']),
    } });
    if (r.hotspots.length) {
      B.push({ p: 'Regional patterns (component share in an area compared with the model\'s own regional mix):' });
      for (const h of r.hotspots) B.push({ p: `- ${compEn(r.category, h.component)}: ${h.ratio}x the model's usual share in ${areaName(h.area)} (${int(h.n)} records).` });
    } else B.push({ p: `No regional pattern met the threshold (at least ${HOTSPOT_RULE.minRecords} records in an area and ${HOTSPOT_RULE.minRatio}x the model's regional mix).` });
  }

  // 5. Durability / repairability
  B.push({ h2: '5. Durability and repairability signals' });
  B.push({ table: {
    cols: [{ label: 'Model', w: 0.18 }, { label: 'Durability (1-5)', w: 0.17, align: 'right' }, { label: 'Repairability (1-5)', w: 0.19, align: 'right' }, { label: 'Mean age at failure', w: 0.2, align: 'right' }, { label: 'Repairs blocked', w: 0.26, align: 'right' }],
    rows: reports.map((r) => (r.scores.sufficient
      ? [r.model, String(r.scores.durability), String(r.scores.repairability), `${r.scores.meanAgeAtFailure} yrs`, pct(r.scores.blockedShare)]
      : [r.model, 'Insufficient data', '-', '-', '-'])),
  } });
  B.push({ small: 'Durability compares mean age at failure with the category\'s reference lifespan. Repairability reflects how often a repair was blocked (no spare, abandoned, or a barrier). Both are early estimates from repair logs, not lab tests.' });

  // 6. Recommendations and alerts
  B.push({ h2: '6. Design recommendations (explainable rules)' });
  const recs = reports.flatMap((r) => r.recommendations.map((x) => ({ ...x, model: r.model })));
  if (!recs.length) B.push({ p: insufficient ? 'Insufficient data: no recommendations.' : 'No rule matched for components with enough records.' });
  for (const x of recs) B.push({ p: `- ${x.model}: ${x.action}. Why: ${x.why} (n=${int(x.n)})` });
  const alerts = reports.flatMap((r) => r.alerts.map((a) => ({ ...a, model: r.model })));
  if (alerts.length) {
    B.push({ h3: 'Early-warning alerts' });
    for (const a of alerts) B.push({ p: `- ${a.model}: ${a.message}${a.synthetic ? ' [SYNTHETIC DATA]' : ''}` });
    B.push({ small: `Spike detector: ${detector?.detector === 'sagemaker_rcf' ? 'SageMaker Random Cut Forest' : 'statistical check (median and MAD)'}${detector?.at ? `, last run ${String(detector.at).slice(0, 16).replace('T', ' ')} UTC` : ''}.` });
  }

  // 7. Evidence and privacy
  B.push({ h2: '7. Evidence and privacy' });
  B.push({ p: `Every real record (${int(realN)} in scope) comes from a technician diagnosis that required a photo; those photos are held by Punarnava and are not reproduced here. This report contains no customer names, phone numbers, addresses, pincodes, owner links, job IDs, photos, notes or individual cases. Areas are shown only as 3-digit pincode regions, and only when ${HOTSPOT_RULE.minRecords} or more records support a pattern.` });

  // 8. Methodology
  B.push({ h2: '8. Methodology, minimum sample sizes and limitations' });
  for (const line of [
    'Source: owner decisions on Punarnava where the owner consented to anonymous data sharing. Each record adds counters for one model and one failed component. Decisions without consent are not counted.',
    `Minimum sample: a component needs ${MIN_SAMPLE} records before causes, regions, barriers or recommendations are reported; smaller groups are marked Insufficient.`,
    'Shares are within one model. Models are listed alphabetically and are never ranked by raw counts, because counts mostly reflect how many units were sold.',
    dated
      ? `Date filter: applied to monthly failure counts (the "In period" column). Cause, age, region, severity and barrier breakdowns cover all records, because those counters are not stored per month.`
      : 'Date filter: none selected; all months on record are included.',
    'Synthetic data: generated with deliberately planted patterns to test the dashboard, flagged on every record and shown as synthetic in this report. It is never counted in public impact figures.',
    'Severity is recorded for real diagnoses only; synthetic and older records have none.',
    'Recommendations are plain rules (for example, voltage surge is 40% or more of a component\'s causes) and each shows the evidence that triggered it. No environmental impact figures (CO2, water) are estimated.',
    'This PDF uses English because standard PDF fonts cannot draw Indian scripts; the on-screen report and print view follow the app language.',
  ]) B.push({ p: `- ${line}` });

  return {
    facts,
    doc: {
      title: `Punarnava report: ${brand}`,
      info: { title: `Punarnava component report: ${brand} (${scope})`, subject: `${period}; ${n} records; ${pct(synShare)} synthetic`, created: generatedAt },
      footer: `Punarnava component report: ${brand}, ${scope}, generated ${String(generatedAt).slice(0, 10)}${synN ? ', contains synthetic demo data' : ''}`,
      blocks: B,
    },
  };
}

/** Models of `brand` in `category` known to the catalog (for empty-data reports). */
export function catalogModels(brand, category) {
  return BRANDS[brand]?.models?.[category] || [];
}
