#!/usr/bin/env node
// Writes policies/punarnava.cedar from the API route table (backend/src/core/api.js) plus fixed attribute rules.
// Run after adding or changing a route: node scripts/local/gen-cedar.mjs   (backend/test/cedar.test.js checks it is current)
import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
export const POLICY_FILE = path.join(ROOT, 'policies/punarnava.cedar');
const ROLES = ['technician', 'collector', 'recycler', 'brand', 'customer'];

export async function generate() {
  const { routeTable } = await import(path.join(ROOT, 'backend/src/core/api.js'));
  const routes = routeTable();
  const list = (pred) => routes.filter(pred).map((r) => `    Punarnava::Action::"${r.action}"`).join(',\n');
  const block = (id, head, pred, when = '') => {
    const acts = list(pred);
    return acts ? `@id("${id}")\npermit (\n  ${head},\n  action in [\n${acts}\n  ],\n  resource\n)${when};\n` : '';
  };
  const ACTIVE = '\nwhen { principal.status == "active" }';
  const out = [
    '// Punarnava authorization policy (Cedar). GENERATED by scripts/local/gen-cedar.mjs from the API route table;',
    '// edit the generator, not this file. Deny by default: an action that no permit below covers is refused.',
    '//',
    '// Principal: Punarnava::User::"<userId>" in Punarnava::Role::"<role>" and Punarnava::Role::"member";',
    '//            anonymous visitors are Punarnava::User::"anonymous" in Punarnava::Role::"public".',
    '// Attributes: status ("active" | "pending" | "suspended" | "anonymous"), role, brandId, orgType.',
    '// Action:    Punarnava::Action::"<METHOD> <route pattern>".  Resource: Punarnava::Api::"punarnava".',
    '// Context:   brand (the brand a request names, or "").',
    '// Ownership checks on individual records (my job, my pickup, owner tokens) stay in backend/src/core.',
    '',
    block('public', 'principal', (r) => r.access === 'public'),
    block('member-self', 'principal in Punarnava::Role::"member"', (r) => r.access === 'self'),
    block('member-active', 'principal in Punarnava::Role::"member"', (r) => r.access === 'any', ACTIVE),
    ...ROLES.map((role) => block(`role-${role}`, `principal in Punarnava::Role::"${role}"`, (r) => Array.isArray(r.access) && r.access.includes(role), ACTIVE)),
    '@id("admin")\npermit (principal in Punarnava::Role::"admin", action, resource);\n',
    '// Suspended accounts keep only their own profile and inbox.',
    `@id("suspended")\nforbid (principal, action, resource)\nwhen {\n  principal.status == "suspended" &&\n  !(action in [\n${list((r) => r.access === 'self')}\n  ])\n};\n`,
    '// A brand user only ever sees their own brand, whatever brand a request names.',
    `@id("brand-scope")\nforbid (\n  principal in Punarnava::Role::"brand",\n  action in [\n${list((r) => Array.isArray(r.access) && r.access.includes('brand'))}\n  ],\n  resource\n)\nwhen { context.brand != "" && context.brand != principal.brandId };\n`,
    '// Only registered refurbishers list products on ReLife; only registered recyclers confirm deliveries.',
    '@id("refurbishers-list")\nforbid (principal, action == Punarnava::Action::"POST /api/listings", resource)\nunless { principal.orgType == "refurbisher" || principal.orgType == "both" || principal in Punarnava::Role::"admin" };\n',
    '@id("recyclers-confirm")\nforbid (principal, action == Punarnava::Action::"POST /api/pickups/:id/confirm", resource)\nunless { principal.orgType == "recycler" || principal.orgType == "both" || principal in Punarnava::Role::"admin" };\n',
  ].filter(Boolean).join('\n');
  return out;
}

if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) {
  const text = await generate();
  writeFileSync(POLICY_FILE, text);
  console.log(`Wrote ${path.relative(ROOT, POLICY_FILE)} (${text.split('\n').length} lines)`);
}
